export const getDistrictsForState = (state) => {
  if (!INDIA_LOCATION_DATA[state]) return [];
  return Object.keys(INDIA_LOCATION_DATA[state]);
};

export const getVillagesForDistrict = (state, district) => {
  if (!INDIA_LOCATION_DATA[state] || !INDIA_LOCATION_DATA[state][district]) return [];
  const distObj = INDIA_LOCATION_DATA[state][district];
  if (Array.isArray(distObj)) return distObj;
  
  const allVillages = [];
  Object.entries(distObj).forEach(([blockName, villages]) => {
    if (Array.isArray(villages)) {
      villages.forEach(v => {
        if (!allVillages.includes(v)) allVillages.push(v);
      });
    } else if (typeof villages === 'string') {
      if (!allVillages.includes(villages)) allVillages.push(villages);
    }
  });
  return allVillages.length > 0 ? allVillages : [`${district} Sadar`, `${district} Rural`, `${district} East`, `${district} West`, `${district} North`, `${district} South`];
};

